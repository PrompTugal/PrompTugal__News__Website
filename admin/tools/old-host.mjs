#!/usr/bin/env node
// The old address, kept: web-summit.newsroom.sgit.ai redirects to https://promptugal.news, path for path.
//
//   node admin/tools/old-host.mjs [out-dir]     (default: <tmp>/promptugal-old-host; run after a build; never write it
//                                                inside this repository: the gate refuses files the build did not write)
//
// GitHub Pages serves one custom domain per repository and cannot answer with a 301, so the old host needs a small
// Pages site of its own, in the SGit-AI organisation (whose GitHub Pages already answers for the name: its DNS is a
// CNAME to sgit-ai.github.io). This writes that site: for every HTML page the build listed in .generated.txt, a
// stub that redirects to the same path on the new host (a meta refresh, a canonical link and a one-line script, so
// browsers, crawlers and agents all land in the right place); a 404.html that does the same for any other path, query
// and fragment included; CNAME; .nojekyll; a README. Publish the output as the root of that repository, on its default
// branch, with Pages on and the custom domain web-summit.newsroom.sgit.ai (HTTPS enforced). Re-run when pages are added.
//
// What does not move: a reader's meter and vault state are in their browser's storage for the old origin, which the
// new origin cannot read; the vault's derivation constants still name the old host on purpose (REALITY.md).
import fs from 'node:fs'
import path from 'node:path'
import os from 'node:os'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const OLD = 'web-summit.newsroom.sgit.ai', NEW = 'https://promptugal.news/'
const out = path.resolve(process.argv[2] || path.join(os.tmpdir(), 'promptugal-old-host'))
const listed = path.join(ROOT, '.generated.txt')
if (!fs.existsSync(listed)) { console.error('no .generated.txt: run node admin/build/build.mjs first'); process.exit(1) }

const esc = s => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;')
const stub = to => `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<title>PrompTugal.news has moved</title>
<meta name="robots" content="noindex">
<link rel="canonical" href="${esc(to)}">
<meta http-equiv="refresh" content="0; url=${esc(to)}">
<script>location.replace(${JSON.stringify(to)} + location.search + location.hash)</script>
</head><body><p>This newsroom is now PrompTugal.news: <a href="${esc(to)}">${esc(to)}</a>.</p></body></html>
`
const fallback = `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<title>PrompTugal.news has moved</title>
<meta name="robots" content="noindex">
<script>location.replace(${JSON.stringify(NEW.slice(0, -1))} + location.pathname + location.search + location.hash)</script>
</head><body><p>This newsroom is now PrompTugal.news: <a href="${NEW}">${NEW}</a>.</p></body></html>
`
// it replaces the output folder, so it refuses one inside this repository or one that is not an earlier output of its own
if (out === ROOT || out.startsWith(ROOT + path.sep)) { console.error(`${out} is inside the repository: write it elsewhere`); process.exit(1) }
if (fs.existsSync(out) && fs.readdirSync(out).length && (fs.existsSync(path.join(out, 'CNAME')) ? fs.readFileSync(path.join(out, 'CNAME'), 'utf8').trim() : '') !== OLD) { console.error(`${out} is not empty and not an earlier output of this tool: refusing to replace it`); process.exit(1) }
fs.rmSync(out, { recursive: true, force: true })
const write = (rel, text) => { const p = path.join(out, rel); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, text) }
let n = 0
for (const rel of fs.readFileSync(listed, 'utf8').split('\n').map(s => s.trim()).filter(Boolean)) {
    if (!/\.(html|md)$/.test(rel) || rel === '404.html' || rel === '404.md') continue
    // a twin (.md) would be served as text, so it cannot redirect itself: it gets no stub and falls to 404.html,
    // which sends the reader on to the same .md on the new host
    if (rel.endsWith('.md')) continue
    write(rel, stub(NEW + rel.replace(/(^|\/)index\.html$/, '$1'))); n++
}
write('404.html', fallback)
write('CNAME', OLD + '\n')
write('.nojekyll', '')
write('README.md', `# ${OLD}\n\nThe old address of PrompTugal.news (https://promptugal.news). Every page here redirects to the same path there.\nGenerated by \`admin/tools/old-host.mjs\` in PrompTugal/PrompTugal__News__Website; do not edit by hand.\n`)
console.log(`${out}: ${n} page stubs, 404.html, CNAME (${OLD})`)
