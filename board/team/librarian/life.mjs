#!/usr/bin/env node
// The agents' life and keys: every agent that holds a key in board/keys.json or commits under its own handle, with its
// keys (active and superseded), its last own commit, its status.json, and what that says about its life cycle.
// Dinis, 9 November 2026, about 11:25 UTC (board/guidance/2026-11-09-how-we-work.md): "every device, every installation,
// every application needs to have its own key" (map them); a scheduled agent that has done nothing for a while is stopped,
// one silent for about a day is archived. This file maps; it stops, archives and changes nothing (the conductors do).
// Writes board/team/librarian/life.json and life.md. Node 18+, no dependencies. Run from the repository root.
import fs from 'node:fs'
import { execFileSync } from 'node:child_process'

const NOW = new Date()
const HOURS = (t) => (NOW - new Date(t)) / 36e5
const SILENT_H = 24
const read = (p, d = null) => { try { return JSON.parse(fs.readFileSync(p, 'utf8')) } catch { return d } }
const day = (t) => (t ? t.replace(/:\d\d(\.\d+)?(Z|[+-]\d\d:\d\d)$/, 'Z').replace('T', ' ') : '')

// keys: every entry, grouped by agent
const keys = (read('board/keys.json', { keys: [] }).keys || []).filter((k) => k.agent)
const agents = new Map()
const get = (h) => { const k = h.toLowerCase(); if (!agents.has(k)) agents.set(k, { handle: h, keys: [], last_commit: null, commits_7d: 0 }); return agents.get(k) }
for (const k of keys) get(k.agent).keys.push({ id: k.id, status: k.status || 'active', fingerprint: (k.bundle || {}).signing_fingerprint || null, superseded_at: k.superseded_at || null })

// commits: the agents' own (CI's "site vX.Y.Z: <subject>" repeats an agent's subject and is skipped)
const log = execFileSync('git', ['log', '--since=7 days ago', '--format=%aI%x09%an%x09%s'], { encoding: 'utf8', maxBuffer: 64 << 20 })
for (const line of log.split('\n')) {
  const [at, author, subject] = line.split('\t')
  if (!subject || author === 'GitHub Actions' || /^site v\d/.test(subject)) continue
  const m = /^([a-z0-9][a-z0-9.-]*@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+):/.exec(subject)
  if (!m) continue
  const a = get(m[1])
  a.commits_7d++
  if (!a.last_commit || at > a.last_commit) a.last_commit = at
}

// paused at Dinis's word: the last "Still paused:" line of the summit set's guidance (board/guidance/2026-11-09-the-summit-set.md)
const SET = 'board/guidance/2026-11-09-the-summit-set.md'
const pausedLine = fs.existsSync(SET) ? (fs.readFileSync(SET, 'utf8').split('\n').filter((l) => /\*\*Still paused:\*\*/.test(l)).pop() || '') : ''
const paused = new Set([...pausedLine.matchAll(/\b([a-z][a-z0-9.-]*)@/g)].map((m) => m[1].replace(/\.$/, '')))

// status.json, for this site's own agents (board/team/<role>/)
for (const a of agents.values()) {
  const role = a.handle.split('@')[0]
  const s = /@PrompTugal\.dinis$/i.test(a.handle) ? read(`board/team/${role}/status.json`) : null
  a.status_updated = s && (s.updated || s.updated_at) ? String(s.updated || s.updated_at) : null
  a.state = s && s.state ? String(s.state).slice(0, 120) : null
  const active = a.keys.filter((k) => k.status === 'active')
  a.flags = []
  const teamSite = /@web-summit\./i.test(a.handle) // the Web Summit team's agents keep their keys on the team's site
  const dotted = /^[a-z0-9-]+\.[a-z0-9-]+@/i.test(a.handle) // a dotted worker pushes to work/<role>; dev@ brings it onto dev
  const isPaused = /@PrompTugal\.dinis$/i.test(a.handle) && paused.has(role)
  a.paused = isPaused
  a.note = isPaused ? `paused at Dinis's word (${SET})` : teamSite ? "keys on the team's site (SGit-AI__Website__Web-Summit), not here; its agents are off at that team's and Dinis's call (the summit set)" : dotted ? `works on work/${role}; its work reaches dev through its main agent's review` : null
  if (active.length > 1) a.note = [a.note, `${active.length} active keys, one per purpose (Dinis: a key for every application)`].filter(Boolean).join('; ')
  if (!active.length && a.commits_7d && !teamSite) a.flags.push('commits with no active key')
  if (a.keys.length && !a.commits_7d && !dotted) a.flags.push('a key, no commit in 7 days')
  if (a.last_commit && HOURS(a.last_commit) > SILENT_H && !isPaused && !teamSite) a.flags.push(`silent ${Math.round(HOURS(a.last_commit))} h`)
}

const rows = [...agents.values()].sort((x, y) => (y.last_commit || '').localeCompare(x.last_commit || ''))
const out = {
  about: 'Every agent with a key in board/keys.json or commits under its own handle in the last 7 days: its keys, its last own commit, its status.json, and life-cycle flags (Dinis, 9 November 2026: idle agents stopped, silent about a day archived). Generated by board/team/librarian/life.mjs at each librarian wake; never hand-edited; changes nothing.',
  generated: NOW.toISOString().replace(/\.\d+Z$/, 'Z'), silent_after_hours: SILENT_H,
  counts: { agents: rows.length, keys: keys.length, active_keys: keys.filter((k) => (k.status || 'active') === 'active').length, flagged: rows.filter((r) => r.flags.length).length },
  agents: rows,
}
fs.writeFileSync('board/team/librarian/life.json', JSON.stringify(out, null, 1) + '\n')

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|')
const md = ['---', 'title: "The agents\' life and keys: who holds which key, who last worked when"', 'by: librarian@PrompTugal.dinis', `generated: ${out.generated}`,
  'source: board/keys.json, git log (the agents\' own commits, 7 days), board/team/*/status.json; board/team/librarian/life.mjs; never hand-edited', '---',
  '# The agents\' life and keys', '',
  `Dinis, 9 November 2026 (\`board/guidance/2026-11-09-how-we-work.md\`): every device, installation and application has its own key, mapped; a scheduled agent idle for a while is stopped, one silent for about a day archived. This is the map; it changes nothing. ${out.counts.agents} agents, ${out.counts.keys} keys (${out.counts.active_keys} active), ${out.counts.flagged} flagged. "Silent" counts from the agent's last own commit; an agent paused at Dinis's word is silent on purpose (\`board/guidance/2026-11-09-the-summit-set.md\`).`, '',
  '| Agent | Active key | Superseded | Last own commit on dev (UTC) | Commits, 7 days | status.json updated | Flags | Note |', '|---|---|---|---|---|---|---|---|']
for (const r of rows) {
  const act = r.keys.filter((k) => k.status === 'active').map((k) => '`' + k.id + '`').join(', ') || 'none'
  const sup = r.keys.filter((k) => k.status !== 'active').length
  md.push(`| ${esc(r.handle)} | ${act} | ${sup || ''} | ${day(r.last_commit)} | ${r.commits_7d || ''} | ${esc(r.status_updated || '')} | ${esc(r.flags.join('; '))} | ${esc(r.note || '')} |`)
}
fs.writeFileSync('board/team/librarian/life.md', md.join('\n') + '\n')
console.log(`life: ${out.counts.agents} agents, ${out.counts.keys} keys (${out.counts.active_keys} active), ${out.counts.flagged} flagged`)
