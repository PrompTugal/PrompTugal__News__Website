// The four indexes: headings to card ids. indexes/title.json (the inverted form of each title), subject.json
// (from the about links to a subject heading), agent.json (made and changed, by authority id), series.json
// (a pass, desk or agent folder to the cards that are part of it, and the ideas ledger's themes).
import { cmp, indexJson, GENERATOR } from './util.mjs'
import { formIndex } from './authority.mjs'



// "The newsroom search" -> "newsroom search, the": the card is found under the word that matters
export function invertTitle(title) {
  const t = String(title || '').replace(/\s+/g, ' ').trim()
  if (!t) return ''
  const m = /^(the|a|an) (.+)$/i.exec(t)
  return m ? `${m[2]}, ${m[1].toLowerCase()}` : t
}

export function buildIndexes(ctx, cards) {
  const head = (what) => ({ about: `${what} Generated by ${GENERATOR} from the cards; never edited by hand.`, cards: cards.length })
  const files = {}

  const title = {}
  for (const c of cards) {
    const h = invertTitle(c.title)
    if (!h) continue
    ;(title[h] = title[h] || []).push(c.id)
  }
  for (const k of Object.keys(title)) title[k].sort(cmp)
  files['indexes/title.json'] = indexJson({ ...head('Title index: the card\'s title in inverted form (a leading The, A or An moves to the end), mapping to the ids of the cards with that title.'), headings: Object.keys(title).length }, 'headings', title)

  const subject = {}
  for (const c of cards) for (const l of c.links) if (l.rel === 'about' && l.to.startsWith('subj:')) (subject[l.to] = subject[l.to] || []).push(c.id)
  for (const k of Object.keys(subject)) subject[k].sort(cmp)
  files['indexes/subject.json'] = indexJson({ ...head('Subject index: a subject of vocabulary/subjects.json, mapping to the cards that are about it (at most three subjects a card).'), headings: Object.keys(subject).length }, 'headings', subject)

  const fidx = formIndex(ctx.authority.records)
  const agent = {}
  const add = (a, kind, id) => { ((agent[a] = agent[a] || {})[kind] = agent[a][kind] || []).push(id) }
  for (const c of cards) {
    for (const l of c.links) if (l.rel === 'made_by') add(l.to, 'made', c.id)
    const ch = c.provenance && c.provenance.changed && c.provenance.changed.by
    const a = ch ? fidx.get(String(ch).toLowerCase()) : null
    if (a) add(a, 'changed', c.id)
  }
  for (const a of Object.keys(agent)) for (const k of Object.keys(agent[a])) agent[a][k].sort(cmp)
  files['indexes/agent.json'] = indexJson({ ...head('Agent index: an authority id of authority/agent.json, mapping to the cards the agent made and those it last changed (from git, as the catalogue read it).'), headings: Object.keys(agent).length }, 'headings', agent)

  const series = {}
  for (const c of cards) {
    for (const l of c.links) if (l.rel === 'part_of') (series[l.to] = series[l.to] || []).push(c.id)
    if (c.type === 'idea' && c.facts && c.facts.theme) (series['theme:' + c.facts.theme] = series['theme:' + c.facts.theme] || []).push(c.id)
  }
  for (const k of Object.keys(series)) series[k].sort(cmp)
  files['indexes/series.json'] = indexJson({ ...head('Series index: a pass, a desk or an agent folder (a card id), or an ideas-ledger theme, mapping to the cards that are part of it.'), headings: Object.keys(series).length }, 'headings', series)
  return { files, counts: { title: Object.keys(title).length, subject: Object.keys(subject).length, agent: Object.keys(agent).length, series: Object.keys(series).length } }
}
