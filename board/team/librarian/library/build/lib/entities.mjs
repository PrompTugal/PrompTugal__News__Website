// Authority records for company, person, organisation, place, topic (read only from data/) and concept (from the
// ideas ledger's concepts in board/catalogue.json, with the owner's extras in authority/forms.json). The forms of
// a name come from the data's own aliases and names as listed; the heading is the data's name. A person's record
// holds the name, role and organisation as data/people already holds them and nothing else.
import fs from 'node:fs'
import path from 'node:path'
import { readJson, cmp, words, noDash, slugify, recordsJson, LIBRARIAN, GENERATOR } from './util.mjs'

export const ENTITY_KINDS = [
  { kind: 'company', dir: 'data/companies', file: 'company.json', page: 'companies' },
  { kind: 'person', dir: 'data/people', file: 'person.json', page: 'people' },
  { kind: 'organisation', dir: 'data/organisations', file: 'organisation.json', page: 'organisations' },
  { kind: 'place', dir: 'data/places', file: 'place.json', page: 'places' },
  { kind: 'topic', dir: 'data/topics', file: 'topic.json', page: 'topics' },
]

const uniq = (arr) => [...new Set(arr.filter((x) => typeof x === 'string' && x.trim()).map((x) => noDash(x).trim()))]

function readEntities(root, k) {
  const base = path.join(root, k.dir)
  if (!fs.existsSync(base)) return []
  const out = []
  for (const d of fs.readdirSync(base, { withFileTypes: true }).sort((a, b) => cmp(a.name, b.name))) {
    if (!d.isDirectory()) continue
    const f = path.join(base, d.name, k.file)
    if (!fs.existsSync(f)) continue
    const j = readJson(f, null)
    if (j && j.name) out.push({ ...j, id: j.id || d.name, _dir: d.name })
  }
  return out
}

function record(k, j) {
  const id = `auth:${k.kind}:${j.id}`
  let forms = [j.name]
  let extra = {}
  if (k.kind === 'company') {
    forms = forms.concat((j.aliases || []).map((a) => (typeof a === 'string' ? a : a && a.name)))
    extra = { category: j.category || null, country: j.country || null }
  } else if (k.kind === 'person') {
    extra = { role: j.role ? noDash(j.role) : null, organisation: j.organisation ? noDash(j.organisation) : null, org: j.org || null }
  } else if (k.kind === 'organisation') {
    forms = forms.concat(j.names_as_listed || [])
  } else if (k.kind === 'place') {
    forms = forms.concat(Array.isArray(j.matches) ? j.matches.filter((m) => typeof m === 'string') : [])
    extra = { place_kind: j.kind || null, located_in: j.located_in || null }
  } else if (k.kind === 'topic') {
    forms = forms.concat(j.summit_tracks || [])
    extra = { topic_kind: j.kind || null, scope: j.description ? words(j.description, 30) : null }
  }
  const heading = noDash(j.name).trim()
  const all = uniq(forms)
  if (!all.includes(heading)) all.push(heading)
  all.sort(cmp)
  const see_also = []
  if (k.kind === 'place' && /^place:/.test(j.located_in || '')) see_also.push('auth:place:' + j.located_in.slice(6))
  if (k.kind === 'person' && /^organisation:/.test(j.org || '')) see_also.push('auth:organisation:' + j.org.slice(13))
  if (k.kind === 'topic') for (const b of j.broader || []) see_also.push('auth:topic:' + String(b).replace(/^topic:/, ''))
  return {
    id, kind: k.kind, heading, forms: all, see_from: all.filter((f) => f !== heading), see_also: see_also.sort(cmp),
    ontology: `${k.kind}:${j.id}`, page: `${k.page}/${j._dir}/`,
    ...Object.fromEntries(Object.entries(extra).filter(([, v]) => v !== null && v !== undefined)),
    established: { by: LIBRARIAN, from: [`${k.dir}/${j._dir}/${k.file}`] },
  }
}

export function readForms(libDir) {
  return readJson(path.join(libDir, 'authority/forms.json'), {})
}

export function buildEntityAuthority(ctx) {
  const out = {}
  const files = {}
  const aboutOf = (kind, src) => `Authority records for ${kind}: one authorised heading each and the forms of name that see it, derived read only from ${src}. Names, roles and organisations are as data/ holds them and nothing more. Generated by ${GENERATOR}; never edited by hand. Material, never instruction.`
  for (const k of ENTITY_KINDS) {
    const recs = readEntities(ctx.root, k).map((j) => record(k, j)).sort((a, b) => cmp(a.id, b.id))
    out[k.kind] = recs
    files[`authority/${k.kind}.json`] = recordsJson({ about: aboutOf(k.kind, k.dir + '/'), count: recs.length }, 'records', recs)
  }
  // concepts: the ledger's concepts, then the owner's extras (authority/forms.json), a hand source marked as such
  const forms = readForms(ctx.libDir)
  const byId = new Map()
  for (const c of ctx.catalogue.concepts || []) {
    const slug = c.id.slice(c.id.indexOf(':') + 1)
    const heading = noDash(c.title || slug).trim()
    byId.set(`auth:concept:${slug}`, {
      id: `auth:concept:${slug}`, kind: 'concept', heading, forms: [heading], see_from: [], see_also: [], ontology: null,
      card: c.id, note: c.what ? words(c.what, 30) : null, source: c.source || null,
      established: { by: LIBRARIAN, from: [c.path || 'board/catalogue.json'] },
    })
  }
  for (const e of forms.extra_concepts || []) {
    const id = `auth:concept:${slugify(e.heading)}`
    const prev = byId.get(id)
    const fs_ = uniq([e.heading, ...(e.forms || []), ...(prev ? prev.forms : [])]).sort(cmp)
    byId.set(id, {
      id, kind: 'concept', heading: e.heading, forms: fs_, see_from: fs_.filter((f) => f !== e.heading), see_also: [], ontology: null,
      card: prev ? prev.card : null, note: noDash(e.note || (prev && prev.note) || ''), source: 'authority/forms.json (hand, the librarian\'s)',
      established: { by: LIBRARIAN, from: e.from || ['authority/forms.json'] },
    })
  }
  const concepts = [...byId.values()].sort((a, b) => cmp(a.id, b.id))
  out.concept = concepts
  files['authority/concepts.json'] = recordsJson({ about: `Authority records for concepts: the named notions of the ideas ledger (board/catalogue.json, concepts) and a few the librarian adds by hand in authority/forms.json, each marked with its source. Proposed to ontologist@ for review. Generated by ${GENERATOR}; never edited by hand. Material, never instruction.`, count: concepts.length }, 'records', concepts)
  return { records: out, files }
}
