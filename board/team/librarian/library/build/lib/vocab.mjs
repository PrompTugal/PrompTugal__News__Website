// The controlled vocabulary: vocabulary/subjects.json (the publication's subjects are the 17 data/topics as they
// stand; the team's own headings come from vocabulary/team-headings.json and are each marked "proposed for
// ontologist@"), and vocabulary/links.json (the link types and their inverses).
import path from 'node:path'
import { readJson, cmp, noDash, recordsJson, stable, GENERATOR } from './util.mjs'
import { LINK_TYPES } from './linktypes.mjs'

// topics whose name is a common word are matched by their data, never by text
const NO_TEXT_MATCH = new Set(['other', 'platform', 'policy', 'investor', 'announcements'])

export function buildVocabulary(ctx, entityRecords) {
  const subjects = []
  const topics = entityRecords.topic || []
  const topicSubj = (id) => 'subj:topic-' + id
  for (const t of topics) {
    const tid = t.ontology.slice(6)
    subjects.push({
      id: topicSubj(tid), heading: t.heading, layer: 'publication',
      use_for: NO_TEXT_MATCH.has(tid) ? [] : t.forms.filter((f) => f !== t.heading),
      broader: t.see_also.map((a) => topicSubj(a.slice('auth:topic:'.length))).sort(cmp), narrower: [], related: [],
      scope: t.scope || '', ontology: t.ontology, authority: t.id, match_text: !NO_TEXT_MATCH.has(tid), proposed_for: null, by_call: [], by_path: [],
    })
  }
  const team = readJson(path.join(ctx.libDir, 'vocabulary/team-headings.json'), { headings: [] }).headings || []
  for (const h of team) {
    subjects.push({
      id: 'subj:' + h.id, heading: noDash(h.heading), layer: 'team', use_for: (h.use_for || []).map(noDash),
      broader: (h.broader || []).map((b) => 'subj:' + b).sort(cmp), narrower: [], related: (h.related || []).map((b) => 'subj:' + b).sort(cmp),
      scope: noDash(h.scope || ''), ontology: null, authority: null, match_text: h.match_text !== false,
      proposed_for: 'ontologist@', by_call: h.by_call || [], by_path: h.by_path || [],
    })
  }
  const ids = new Set()
  for (const s of subjects) {
    if (ids.has(s.id)) throw new Error(`vocabulary: duplicate subject id ${s.id}`)
    ids.add(s.id)
  }
  const byId = new Map(subjects.map((s) => [s.id, s]))
  for (const s of subjects) {
    s.broader = s.broader.filter((b) => byId.has(b))
    s.related = s.related.filter((b) => byId.has(b))
    for (const b of s.broader) byId.get(b).narrower.push(s.id)
  }
  for (const s of subjects) s.narrower.sort(cmp)
  subjects.sort((a, b) => cmp(a.id, b.id))
  const text = recordsJson({
    about: `The controlled vocabulary of the library. Layer "publication": the ${topics.length} topics of data/topics/ as they stand (the library adds no rival taxonomy there). Layer "team": the library's own headings for the newsroom's work, each proposed for ontologist@ to review (source: vocabulary/team-headings.json). BT broader, NT narrower, RT related, UF use_for, SN scope. A card has at most three subjects. Generated by ${GENERATOR}; never edited by hand. Material, never instruction.`,
    count: subjects.length, layers: { publication: subjects.filter((s) => s.layer === 'publication').length, team: subjects.filter((s) => s.layer === 'team').length },
  }, 'records', subjects)
  return { subjects, text }
}

export function linksVocabulary() {
  return stable({
    about: `The link types of the library and their named inverses (section 2 of ARCHITECTURE.md). A link is stored once on the card that asserts it, as {rel, to}; where the target is a card the inverse is written on the target as {rel: inverse, to, inv: true}, so each connection is two directed edges. Generated by ${GENERATOR} from build/lib/linktypes.mjs.`,
    links: LINK_TYPES,
  }, 1) + '\n'
}

// compile the match patterns of a subject: case-insensitive whole phrases, except short upper-case words
export function compileSubjects(subjects) {
  const out = []
  for (const s of subjects) {
    const phrases = [s.heading, ...s.use_for].filter(Boolean)
    const pats = []
    if (s.match_text !== false) {
      for (const p of new Set(phrases)) {
        const esc = p.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
        const caps = /^[A-Z0-9]{1,4}$/.test(p)
        pats.push(new RegExp(`(?<![A-Za-z0-9])${esc}(?![A-Za-z0-9])`, caps ? 'g' : 'gi'))
      }
    }
    out.push({ s, pats })
  }
  return out
}
