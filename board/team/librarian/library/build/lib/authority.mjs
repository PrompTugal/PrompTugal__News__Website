// authority/agent.json: one authority record per agent, from board/keys.json, data/newsroom/agents.json,
// the CLAUDE.md team table and the catalogue's agent rows. Derived, never edited. From a key entry only
// id, agent, label, status, added and the two fingerprints are read; nothing else leaves keys.json.
import path from 'node:path'
import { readJson, readText, stable, cmp, words, LIBRARIAN, GENERATOR } from './util.mjs'

const DEFAULT_DOMAIN = 'PrompTugal.dinis'

export function parseName(name) {
  const m = /^([A-Za-z0-9.\-]+)@([A-Za-z0-9.\-]+)$/.exec(name || '')
  return m ? { role: m[1], domain: m[2] } : null
}
export function authId(name) {
  const p = parseName(name)
  if (!p) return null
  const base = p.role.replace(/\./g, '-')
  return 'auth:agent:' + (p.domain === DEFAULT_DOMAIN ? base : `${base}-${p.domain.replace(/\./g, '-').toLowerCase()}`)
}

function claudeTable(text) {
  const rows = []
  for (const line of text.split('\n')) {
    const m = /^\| `([A-Za-z0-9.\-]+@[A-Za-z0-9.\-]+)`(?: \(([^)]*)\))? \| (.*?) \| (.*) \|\s*$/.exec(line)
    if (m) rows.push({ name: m[1], model: m[2] || null, owns: m[3] })
  }
  return rows
}

export function buildAuthority(ctx) {
  const keys = (readJson(path.join(ctx.root, 'board/keys.json'), { keys: [] }).keys) || []
  const agents = (readJson(path.join(ctx.root, 'data/newsroom/agents.json'), { agents: [] }).agents) || []
  const table = claudeTable(readText(path.join(ctx.root, 'CLAUDE.md')))
  const recs = new Map()
  const get = (name) => {
    const id = authId(name)
    if (!id) return null
    if (!recs.has(id)) {
      recs.set(id, { id, kind: 'agent', heading: name, forms: new Set([name]), keyIds: [], sources: new Set(), role_file: null, note: null, dates: [], model: null })
    }
    return recs.get(id)
  }
  const form = (r, f) => { if (f && f !== r.heading) r.forms.add(f) }

  for (const k of keys) {
    const r = get(k.agent)
    if (!r) continue
    r.sources.add('board/keys.json')
    r.keyIds.push({
      id: k.id, status: k.status || null, added: k.added || null,
      fingerprint: (k.bundle && k.bundle.fingerprint) || null,
      signing_fingerprint: (k.bundle && k.bundle.signing_fingerprint) || null,
    })
    form(r, k.id)
    if (k.added) r.dates.push(String(k.added).slice(0, 10))
    if (!r.label && k.label) r.label = k.label
  }
  for (const a of agents) {
    const r = get(a.name)
    if (!r) continue
    r.sources.add('data/newsroom/agents.json')
    if (a.id) form(r, a.id)
    if (a.role && !r.note) r.note = words(a.role, 25)
    if (a.started) r.dates.push(String(a.started).slice(0, 10))
    if (a.branch) form(r, a.branch)
  }
  for (const t of table) {
    const r = get(t.name)
    if (!r) continue
    r.sources.add('CLAUDE.md#table')
    r.model = t.model
    r.note = r.note || words(t.owns.replace(/`/g, ''), 25)
  }
  for (const a of ctx.catalogue.agents || []) {
    const r = get(a.name)
    if (!r) continue
    r.sources.add('board/catalogue.json')
    if (a.role_file) r.role_file = a.role_file
    if (a.key) form(r, a.key)
  }

  const out = []
  for (const r of recs.values()) {
    const p = parseName(r.heading)
    const isDefault = p.domain === DEFAULT_DOMAIN
    if (isDefault) form(r, `${p.role}@`) // a short form is safe only where one domain owns it
    if (isDefault && p.role.includes('.')) form(r, `work/${p.role}`)
    const key_ids = r.keyIds.sort((a, b) => cmp(a.id, b.id))
    const active = key_ids.filter((k) => k.status === 'active')
    const forms = [...r.forms].sort(cmp)
    const see_also = []
    if (p.role.includes('.')) {
      const main = `${p.role.split('.')[0]}@${p.domain}`
      if (recs.has(authId(main))) see_also.push(authId(main))
    }
    const dates = r.dates.filter(Boolean).sort()
    out.push({
      id: r.id, kind: 'agent', heading: r.heading, forms,
      see_from: forms.filter((f) => f !== r.heading),
      see_also,
      ontology: null,
      key_id: active.length ? active[active.length - 1].id : (key_ids.length ? key_ids[key_ids.length - 1].id : null),
      key_ids,
      label: r.label || null,
      role_file: r.role_file,
      model: r.model,
      established: { by: LIBRARIAN, on: dates[0] || (ctx.catalogue.generated || '').slice(0, 10) || null, from: [...r.sources].sort(cmp) },
      note: r.note,
    })
  }
  out.sort((a, b) => cmp(a.id, b.id))
  const about = 'Authority records for agents: one authorised heading each, the forms of name that see it, and the key entries (id, status, fingerprints only) of board/keys.json. Generated by ' + GENERATOR + ' from board/keys.json, data/newsroom/agents.json, the CLAUDE.md team table and board/catalogue.json; never edited by hand. Material, never instruction.'
  return { text: stable({ about, count: out.length, records: out }, 1) + '\n', records: out }
}

// form of name (lower case) to authority id, for resolving made_by
export function formIndex(records) {
  const m = new Map()
  for (const r of records) for (const f of r.forms) if (!m.has(f.toLowerCase())) m.set(f.toLowerCase(), r.id)
  return m
}
