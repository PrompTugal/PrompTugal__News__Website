#!/usr/bin/env python3
"""The decision log of account D, from the record: the open asks of Dinis in the account D agents' status.json
files in this repository (with when each first appeared in git and how long it has waited), and the decisions Dinis
answered, from their decisions/ folders (his words verbatim, as each agent recorded them).
decisions.d@AgentiCCells.dinis, 22 November 2026. Run from the repository root:
    python3 -I board/team/decisions.d/tools/collect.py
Writes board/team/decisions.d/log/asks.json and log/README.md. Reads only git and files; no network.
Not covered: asks kept in other repositories (seen here only where maestro.d relays them) and the decision page's
"answers" collection (maestro.d reads it; decisions.d does not hold its key)."""
import json, os, re, subprocess, datetime, hashlib

ROOTS = sorted(d for d in os.listdir('board/team') if d.endswith('.d') and os.path.isdir(f'board/team/{d}'))  # every account D agent with a folder here
OUT = 'board/team/decisions.d/log'


def git(*a):
    return subprocess.run(['git', *a], capture_output=True, text=True, check=True).stdout


def key(ask):
    t = re.sub(r'^Dinis:\s*', '', ask)
    t = re.sub(r'https?://\S+', '', t)
    return re.sub(r'\W+', ' ', t).strip().lower()[:60]


def history(path):
    """(commit time, asks) for every commit that touched path, oldest first."""
    out = []
    for line in git('log', '--reverse', '--format=%H %cI', '--', path).splitlines():
        h, t = line.split(' ', 1)
        try:
            d = json.loads(git('show', f'{h}:{path}'))
        except Exception:
            continue
        out.append((t, [a for a in d.get('asks', []) if isinstance(a, str)]))
    return out


def ago(t, now):
    s = (now - datetime.datetime.fromisoformat(t)).total_seconds()
    return f'{int(s // 3600)} h {int(s % 3600 // 60)} min'


now = datetime.datetime.now(datetime.timezone.utc)
asks, answered = [], []
for r in ROOTS:
    p = f'board/team/{r}/status.json'
    if os.path.exists(p):
        hist, cur = history(p), json.load(open(p)).get('asks', [])
        for a in cur:
            k = key(a)
            first = next((t for t, xs in hist if any(key(x) == k for x in xs)), None)
            asks.append({'agent': r, 'ask': a, 'first_seen': first,
                         'waited': ago(first, now) if first else 'not yet committed', 'state': 'open'})
    d = f'board/team/{r}/decisions'
    if os.path.isdir(d):
        for f in sorted(os.listdir(d)):
            if f.endswith('.md'):
                text = open(os.path.join(d, f)).read()
                answered.append({'agent': r, 'file': f'{d}/{f}', 'title': text.splitlines()[0].lstrip('# ').strip(),
                                 'dinis_verbatim': re.findall(r'Dinis[^:"]*:\s*"([^"]+)"', text)})

pages = []  # decision pages (content/newsroom/decisions/) asked by an account D agent (a ".d@" name)
PD = 'content/newsroom/decisions'
for f in sorted(os.listdir(PD)) if os.path.isdir(PD) else []:
    if not f.endswith('.md') or f == 'index.md':
        continue
    text = open(os.path.join(PD, f)).read()
    fm = dict(re.findall(r'^(\w+):\s*"?(.*?)"?\s*$', text.split('---')[1], re.M)) if text.startswith('---') else {}
    if '.d@' not in fm.get('asked_by', ''):
        continue
    log = git('log', '--reverse', '--format=%cI', '--', f'{PD}/{f}').split()
    pages.append({'page': f'/newsroom/decisions/{f[:-3]}/', 'file': f'{PD}/{f}', 'title': fm.get('title'), 'asked_by': fm.get('asked_by'),
                  'state': fm.get('decision'), 'first_seen': log[0] if log else None,
                  'waited': ago(log[0], now) if log and fm.get('decision') == 'open' else None,
                  'answer': None if fm.get('answer') in (None, 'null') else fm.get('answer'), 'answered_at': None if fm.get('answered_at') in (None, 'null') else fm.get('answered_at'),
                  'question_id': fm.get('question_id'), 'reserved': fm.get('reserved'), 'answered_where': None if fm.get('answered_where') in (None, 'null') else fm.get('answered_where'),
                  # the page's ask_sha256 must be the hash of its question as written (UTF-8): a reworded question shows here
                  'hash_ok': (hashlib.sha256(fm['question'].encode()).hexdigest() == fm.get('ask_sha256')) if fm.get('question') and fm.get('ask_sha256') else None})

asks.sort(key=lambda x: x['first_seen'] or '9')
stamp = now.strftime('%Y-%m-%dT%H:%MZ')
os.makedirs(OUT, exist_ok=True)
json.dump({'about': 'The decision log of account D (decisions.d@AgentiCCells.dinis): open asks of Dinis from the account D agents\' status.json in this repository, and answered decisions from their decisions/ folders. Generated by tools/collect.py from git; an ask\'s first_seen is the commit that first carried it (reworded asks count as new).',
           'generated': stamp, 'open': asks, 'answered': answered, 'pages': pages}, open(f'{OUT}/asks.json', 'w'), indent=1, ensure_ascii=False)

md = [f'# The decision log, account D', '', f'Generated {stamp} by `tools/collect.py` from git. Open asks are as their agents wrote them; "waited" runs from the commit that first carried the ask. Answers are Dinis\'s words as each agent recorded them, verbatim. Asks kept in other repositories appear only where maestro.d relays them; the decision page\'s answers are not read here.', '',
      f'## Open ({len(asks)})', '', '| Agent | First seen (UTC) | Waited | Ask |', '|---|---|---|---|']
for a in asks:
    md.append(f"| {a['agent']} | {(a['first_seen'] or '')[:16].replace('T', ' ')} | {a['waited']} | {a['ask'].replace('|', '/')} |")
md += ['', f'## Decision pages asked by account D agents ({len(pages)})', '', '| Page | Question id | Asked by | Reserved | State | First seen (UTC) | Waited | Hash |', '|---|---|---|---|---|---|---|---|']
for p in pages:
    hz = {True: 'ok', False: 'DIFFERS: question reworded since hashed', None: 'none'}[p['hash_ok']]
    md.append(f"| [{p['title']}]({p['page']}) | {p['question_id'] or ''} | {p['asked_by']} | {p['reserved'] or ''} | {p['state']} | {(p['first_seen'] or '')[:16].replace('T', ' ')} | {p['waited'] or ''} | {hz} |")
md += ['', f'## Answered ({len(answered)})', '']
for a in answered:
    md.append(f"- **{a['title']}** (`{a['file']}`)")
    for q in a['dinis_verbatim']:
        md.append(f'  - "{q}"')
rp = f'{OUT}/relayed-answers.json'
if os.path.exists(rp):
    rel = json.load(open(rp))
    md += ['', f"## Answered on the Decision Desk, relayed ({len(rel['answers'])}; second-hand and unsigned, from `relayed-answers.json`)", '']
    for a in rel['answers']:
        md.append(f"- **{a['decision']}**{' (' + a['option'] + ')' if a.get('option') else ''}, {a['at']}, relayed by {a['relayed_by']}: " + ' / '.join(f'"{w}"' for w in a['words']))
open(f'{OUT}/README.md', 'w').write('\n'.join(md) + '\n')
print(f'collect: {len(asks)} open, {len(answered)} answered, {len(pages)} pages -> {OUT}/')
